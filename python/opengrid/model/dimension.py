"""Point-count propagation through structured domains.

Method: a structured domain needs the same number of points on opposite edges, so changing one
connector's dimension must change the connectors topologically opposite to it, across every
structured domain that uses it (and through the domains that are the faces of blocks, which
share their connectors). The change spreads
breadth first: for each domain using a changed connector, the opposite edge is brought to the
same point count by changing one of its connectors that is still free - the only one when the
edge is a single connector, else the longest (a warning says which) - and that connector's
change spreads on. An edge whose connectors are all fixed by the change already and still
disagrees is a contradiction (an over-constrained loop): the change is refused naming it.
Connectors generated by a sketch are not changed here: their family is set in the sketch.
"""

from opengrid.validation import Issue, ValidationError


def edge_points(edge, dimensions: dict) -> int:
    """Points along a domain edge made of connectors sharing their ends."""
    return sum(dimensions[item["connector"]] for item in edge) - (len(edge) - 1)


def propagate_dimension(store, connector_id: int, dimension: int, lengths=None):
    """{connector id: new dimension} for the connector and every connector that must follow
    it through the structured domains, with warnings (which connector of a several-connector
    edge took the change). ``lengths`` (connector id -> length) picks the longest connector
    of such an edge; without it the first free one is taken."""
    from opengrid.model.sketch import output_owner

    if isinstance(dimension, bool) or not isinstance(dimension, int) or dimension < 2:
        raise ValidationError(
            [Issue(store.get(connector_id).name, f"dimension must be >= 2, got {dimension!r}")]
        )
    current = {e.id: e.params["dimension"] for e in store.entities("connector")}
    uses: dict[int, list] = {}  # connector id -> [(domain, edge index)]
    for domain in store.entities("domain"):
        for k, edge in enumerate(domain.params["edges"]):
            for item in edge:
                uses.setdefault(item["connector"], []).append((domain, k))
    owners = output_owner(store)
    assigned = {connector_id: dimension}
    if assigned[connector_id] == current[connector_id]:
        return {}, []
    warnings = []
    todo = [connector_id]
    while todo:
        changed = todo.pop(0)
        for domain, k in uses.get(changed, []):
            dims = dict(current)
            dims.update(assigned)
            edge = domain.params["edges"][k]
            opposite = domain.params["edges"][(k + 2) % 4]
            points = edge_points(edge, dims)
            if edge_points(opposite, dims) == points:
                continue
            free = [item["connector"] for item in opposite if item["connector"] not in assigned]
            labels = ", ".join(store.get(item["connector"]).name for item in opposite)
            if not free:
                raise ValidationError(
                    [
                        Issue(
                            domain.name,
                            f"edge {k} would have {points} points but the opposite edge "
                            f"{(k + 2) % 4} [{labels}] {edge_points(opposite, dims)}, and every "
                            "connector of it is fixed by this change already: the topology "
                            "ties the two counts together",
                        )
                    ]
                )
            for candidate in free:
                owner = owners.get(candidate)
                if owner is not None:
                    raise ValidationError(
                        [
                            Issue(
                                store.get(candidate).name,
                                f"would have to follow (opposite edge of {domain.name}) but is "
                                f"generated by sketch {owner[0].name!r}: set the dimension in "
                                "the sketch (its edge family) instead",
                            )
                        ]
                    )
            target = free[0]
            if len(free) > 1 and lengths is not None:
                target = max(free, key=lambda c: lengths.get(c, 0.0))
            others = sum(dims[item["connector"]] for item in opposite) - dims[target]
            new_dim = points - others + (len(opposite) - 1)
            name = store.get(target).name
            if new_dim < 2:
                raise ValidationError(
                    [
                        Issue(
                            domain.name,
                            f"edge {k} with {points} points would leave {name} on the opposite "
                            f"edge with {new_dim} points (at least 2)",
                        )
                    ]
                )
            assigned[target] = new_dim
            todo.append(target)
            if len(free) > 1:
                warnings.append(
                    f"{domain.name}: edge {(k + 2) % 4} has several connectors [{labels}]; "
                    f"{name} took the change ({dims[target]} -> {new_dim} points)"
                )
    return {c: d for c, d in assigned.items() if d != current[c]}, warnings
