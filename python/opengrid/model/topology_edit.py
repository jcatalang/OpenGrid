def _line_connector(store, p0, p1, n: int, base: str, distribution=None) -> int:
    curve = fresh_name(store, f"{base}-line")
    _add(store, "line", {"p0": tuple(map(float, p0)), "p1": tuple(map(float, p1))}, curve)
    raw = {"segments": curve, "dimension": int(n)}
    if distribution is not None:
        raw["distribution"] = distribution
    return _add(store, "connector", raw, fresh_name(store, base)).id


def _radial_distribution(spacing):
    if spacing is None:
        return None
    return {"type": "tanh", "begin_spacing": float(spacing)}


def _check_ogrid_options(where, fraction, radial_points):
    if isinstance(fraction, bool) or not isinstance(fraction, (int, float)):
        _fail(where, f"fraction must be a number in (0, 1), got {fraction!r}")
    if not 0.0 < fraction < 1.0:
        _fail(where, f"fraction must lie in (0, 1), got {fraction!r}")
    if radial_points is not None and (
        isinstance(radial_points, bool) or not isinstance(radial_points, int) or radial_points < 2
    ):
        _fail(where, f"radial_points must be an integer >= 2, got {radial_points!r}")


def ogrid_domain(store, name, fraction=0.5, radial_points=None, radial_spacing=None, core=True):
    entity = _entity(store, name, "domain", "ogrid_domain")
    _check_ogrid_options(entity.name, fraction, radial_points)
    if entity.params.get("surface") is not None:
        _fail(entity.name, "lies on a surface; O-grids need planar or spatial (TFI) domains")
    _check_domain_users(store, entity)
    _unused, domains = _evaluators(store)
    grid = np.asarray(domains.grid(entity.id))
    nj, ni = grid.shape[:2]
    corners = [grid[0, 0], grid[0, -1], grid[-1, -1], grid[-1, 0]]  # loop order
    centre = np.mean(corners, axis=0)
    inner = [centre + fraction * (c - centre) for c in corners]
    if radial_points is None:
        radial_points = max(3, (ni + nj) // 4)
    dist = _radial_distribution(radial_spacing)
    base = entity.name
    radial = [
        _line_connector(store, corners[k], inner[k], radial_points, f"{base}-r{k}", dist)
        for k in range(4)
    ]
    counts = (ni, nj, ni, nj)
    inner_edges = [
        _line_connector(store, inner[k], inner[(k + 1) % 4], counts[k], f"{base}-in{k}")
        for k in range(4)
    ]
    outer = [_items(e) for e in entity.params["edges"]]
    generator = entity.params["generator"]
    outer_generator, warnings = _filter_walls(generator, {0})
    created = []
    for k in range(4):
        edges = [
            outer[k],
            [{"connector": radial[(k + 1) % 4], "reversed": False}],
            [{"connector": inner_edges[k], "reversed": True}],
            [{"connector": radial[k], "reversed": True}],
        ]
        domain = _add(
            store,
            "domain",
            {"edges": edges, "generator": outer_generator, "surface": None},
            fresh_name(store, f"{base}-{k}"),
        )
        created.append(domain.id)
    if core:
        edges = [[{"connector": inner_edges[k], "reversed": False}] for k in range(4)]
        domain = _add(
            store,
            "domain",
            {"edges": edges, "generator": None, "surface": None},
            fresh_name(store, f"{base}-core"),
        )
        created.append(domain.id)
    for new in created:
        _add_to_users(store, entity.id, new)
    for dependent in list(store.dependents(entity.id)):
        params = dict(dependent.params)
        if dependent.kind in ("zone", "patch"):
            params["members"] = tuple(m for m in params["members"] if m.get("domain") != entity.id)
        elif dependent.kind == "volume":
            params["faces"] = tuple(f for f in params["faces"] if f != entity.id)
        elif dependent.kind == "smoothing_group":
            params = _group_domains(params, entity.id, [])
        _update(store, dependent.id, params)
    store.remove(entity.id)
    return [store.get(c).name for c in created], warnings


def ogrid_block(store, name, fraction=0.5, radial_points=None, radial_spacing=None, core=True):
    entity = _six_face_block(store, name, "ogrid_block")
    _check_ogrid_options(entity.name, fraction, radial_points)
    result = _block_eval(store, entity.id)
    grid = np.asarray(result["grid"])
    nk, nj, ni = grid.shape[:3]
    if radial_points is None:
        radial_points = max(3, (ni + nj + nk) // 6)
    connectors = ConnectorEvaluator(store)
    corner = {}
    for ci in (0, 1):
        for cj in (0, 1):
            for ck in (0, 1):
                corner[(ci, cj, ck)] = grid[-ck, -cj, -ci]
    centre = np.mean(list(corner.values()), axis=0)
    inner = {c: centre + fraction * (p - centre) for c, p in corner.items()}
    scale = float(np.ptp(grid.reshape(-1, 3), axis=0).max())
    dist = _radial_distribution(radial_spacing)
    base = entity.name
    radial = {
        c: _line_connector(store, corner[c], inner[c], radial_points, f"{base}-r", dist)
        for c in sorted(corner)
    }
    counts = (ni, nj, nk)
    edge_pairs = []
    for c in sorted(corner):
        for axis in range(3):
            if c[axis] == 0:
                d = list(c)
                d[axis] = 1
                edge_pairs.append((c, tuple(d), axis))
    inner_edge = {}
    for c, d, axis in edge_pairs:
        inner_edge[(c, d)] = _line_connector(store, inner[c], inner[d], counts[axis], f"{base}-in")
    # Outer block edges as connector chains, from the face domains' edges.
    outer_edge = {}
    face_ids = list(result["faces"].values())
    for face_id in face_ids:
        for edge in store.get(face_id).params["edges"]:
            points = _chain_points(edge, connectors)
            for c, d, _axis in edge_pairs:
                if _same(points[0], corner[c], scale) and _same(points[-1], corner[d], scale):
                    outer_edge[(c, d)] = _items(edge)
                elif _same(points[0], corner[d], scale) and _same(points[-1], corner[c], scale):
                    outer_edge[(c, d)] = _reverse_chain(edge)
    if len(outer_edge) != 12:
        _fail(entity.name, "its face edges do not form the twelve block edges")
    # Radial faces, one per block edge: outer edge c->d, radial d, inner edge d->c, radial c.
    radial_face = {}
    for c, d, _axis in edge_pairs:
        edges = [
            outer_edge[(c, d)],
            [{"connector": radial[d], "reversed": False}],
            [{"connector": inner_edge[(c, d)], "reversed": True}],
            [{"connector": radial[c], "reversed": True}],
        ]
        radial_face[(c, d)] = _add_face(store, edges, f"{base}-rf").id
    # Inner faces: for each block face (axis, side), its 4 corners in loop order.
    face_corners = {}
    for axis in range(3):
        for side in (0, 1):
            others = [x for x in range(3) if x != axis]
            loop = []
            for a, b in ((0, 0), (1, 0), (1, 1), (0, 1)):
                c = [0, 0, 0]
                c[axis] = side
                c[others[0]] = a
                c[others[1]] = b
                loop.append(tuple(c))
            face_corners[(axis, side)] = loop

    def edge_items(c, d, table):
        if (c, d) in table:
            item = table[(c, d)]
            if isinstance(item, int):
                return [{"connector": item, "reversed": False}]
            return list(item)
        item = table[(d, c)]
        if isinstance(item, int):
            return [{"connector": item, "reversed": True}]
        return _reverse_chain(item)

    inner_face = {}
    for key, loop in face_corners.items():
        edges = [edge_items(loop[m], loop[(m + 1) % 4], inner_edge) for m in range(4)]
        inner_face[key] = _add_face(store, edges, f"{base}-if").id
    # The outer face domain of each block face: the one whose edges are that face's edges.
    outer_face = {}
    for key, loop in face_corners.items():
        wanted = sorted(
            tuple(
                sorted(i["connector"] for i in edge_items(loop[m], loop[(m + 1) % 4], outer_edge))
            )
            for m in range(4)
        )
        for face_id in face_ids:
            have = sorted(
                tuple(sorted(i["connector"] for i in e)) for e in store.get(face_id).params["edges"]
            )
            if have == wanted:
                outer_face[key] = face_id
        if key not in outer_face:
            _fail(entity.name, "could not match a face domain to a block face")
    warnings = []
    created = []
    for key, loop in face_corners.items():
        sides = []
        for m in range(4):
            c, d = loop[m], loop[(m + 1) % 4]
            pair = (c, d)
            if pair not in radial_face:
                pair = (d, c)
            sides.append(radial_face[pair])
        faces = [outer_face[key], inner_face[key], *sides]
        params = _block_params(entity, faces, warnings)
        block = _add(store, "block", params, fresh_name(store, f"{base}-{'ijk'[key[0]]}{key[1]}"))
        created.append(block.id)
    if core:
        params = _block_params(entity, [inner_face[k] for k in sorted(inner_face)], [])
        block = _add(store, "block", params, fresh_name(store, f"{base}-core"))
        created.append(block.id)
    _group_blocks(store, entity.id, created)
    store.remove(entity.id)
    return [store.get(c).name for c in created], warnings


