"""Topology editing: splitting and joining connectors, structured domains and blocks, and O-grid
(butterfly) topologies for structured domains and six-face blocks.

All functions change a store inside an open transaction (they are run by
opengrid.commands.topology.TopologyEdit, so each is one undo step) and return
``(names, warnings)``. Every new or changed entity is validated by the normal parameter
normalisation.

Connectors:
  * split at node k: the connector keeps its name and nodes 0..k; a new connector takes nodes
    k..n-1. The curve chain is cut at the node's arc length (CurveChain.locate_length) and both
    get an explicit distribution with the old nodes' arc-length positions, so the nodes stay
    where they were (to the arc-length inversion accuracy, about 1e-13 of the length).
    Domains, unstructured loops, inflation walls and 2D patches using the connector get both.
  * join two connectors sharing an end: the first keeps its name and runs along both (its
    direction); explicit positions keep all nodes. Every domain or loop must use them
    consecutively, and patches must hold both or neither.
Structured domains:
  * split at an index i or j: the edges crossing the cut are split at that node (splitting
    connectors when needed); the cut becomes a new connector on a polyline through the grid
    line, so the new boundaries follow the old grid exactly. The domain keeps its name for the
    part with the lower index; both parts are regenerated by their generator from the new
    boundaries (their interiors equal the old grid only where the generator reproduces it).
    Walls (Hermite / elliptic) stay on the parts whose edges still carry them; attraction
    lines are dropped (warning). Zones, 3D patches and volumes get the new part too.
  * join two domains sharing a whole edge: the first keeps its name; the shared connectors are
    deleted when nothing else uses them.
Blocks (six-face blocks only):
  * split at an index along i, j or k: the four side faces are split along the matching grid
    line, the four cut connectors bound a new interior face, and the block becomes two.
  * join two blocks sharing a face: the side faces are joined pairwise and the shared face is
    deleted.
O-grids (butterfly / O-H topology):
  * a structured domain becomes a core domain and four domains around it; the core's corners
    are centre + fraction * (corner - centre) (centre = mean of the corners), joined by straight
    connectors, and four radial connectors run from the corners to the core. With
    ``core=False`` the core is left as a hole (an O-grid around a body).
  * a six-face block becomes a core block and six shell blocks the same way (or only the shell).
Blocks used by smoothing walls lose them (face names change with the new orientation); a
warning says so.
"""

import numpy as np

from opengrid.model.connectors import CHAIN_TOLERANCE, EXPLICIT, ConnectorEvaluator
from opengrid.model.entities import normalize_params
from opengrid.validation import Issue, ValidationError

AXES = ("i", "j", "k")


# ----------------------------------------------------------------------------- helpers
def _fail(where: str, message: str):
    raise ValidationError([Issue(where, message)])


def fresh_name(store, base: str) -> str:
    """``base`` if free, else ``base-2``, ``base-3``, ..."""
    if base not in store:
        return base
    k = 2
    while f"{base}-{k}" in store:
        k += 1
    return f"{base}-{k}"


def _add(store, kind: str, raw: dict, name: str):
    params = normalize_params(kind, raw, name, store)
    return store.add(kind, params, name)


def _update(store, entity_id: int, raw: dict):
    entity = store.get(entity_id)
    params = normalize_params(entity.kind, raw, entity.name, store)
    return store.update(entity_id, params=params)


def _entity(store, name, kind, where):
    if isinstance(name, bool) or not isinstance(name, (str, int)) or name not in store:
        _fail(where, f"no entity {name!r}")
    entity = store.get(name)
    kinds = kind
    if isinstance(kind, str):
        kinds = (kind,)
    if entity.kind not in kinds:
        _fail(entity.name, f"is a {entity.kind}, not a {' or '.join(kinds)}")
    return entity


def _evaluators(store):
    from opengrid.model.domains import DomainEvaluator

    connectors = ConnectorEvaluator(store)
    return connectors, DomainEvaluator(store, connectors)


def _items(chain) -> list[dict]:
    return [{"connector": i["connector"], "reversed": bool(i["reversed"])} for i in chain]


def _reverse_chain(chain) -> list[dict]:
    return [{"connector": i["connector"], "reversed": not i["reversed"]} for i in reversed(chain)]


def _replace_in_chain(chain, old: int, new_ids: list[int]) -> list[dict]:
    """Replace connector ``old`` by ``new_ids`` (in old's direction) in a chain of items."""
    out = []
    for item in chain:
        if item["connector"] != old:
            out.append({"connector": item["connector"], "reversed": item["reversed"]})
            continue
        if item["reversed"]:
            out.extend({"connector": c, "reversed": True} for c in reversed(new_ids))
        else:
            out.extend({"connector": c, "reversed": False} for c in new_ids)
    return out


def _chain_counts(chain, connectors) -> list[int]:
    return [len(connectors.nodes(i["connector"]).points) for i in chain]


def _chain_points(chain, connectors) -> np.ndarray:
    parts = []
    for k, item in enumerate(chain):
        points = connectors.nodes(item["connector"]).points
        if item["reversed"]:
            points = points[::-1]
        if k > 0:
            points = points[1:]
        parts.append(points)
    return np.concatenate(parts)


def _same(a, b, scale: float) -> bool:
    return float(np.linalg.norm(np.asarray(a) - np.asarray(b))) <= CHAIN_TOLERANCE * max(1.0, scale)


# -------------------------------------------------------------------------- connectors
def _segments_reversed(segments) -> list[dict]:
    return [{"curve": s["curve"], "t0": s["t1"], "t1": s["t0"]} for s in reversed(segments)]


def _explicit(arc: np.ndarray) -> dict:
    arc = np.asarray(arc, dtype=float)
    positions = (arc - arc[0]) / (arc[-1] - arc[0])
    positions[0] = 0.0
    positions[-1] = 1.0
    return {"type": EXPLICIT, "positions": tuple(float(p) for p in positions)}


def split_connector(store, name, index: int, new_name: str | None = None):
    entity = _entity(store, name, "connector", "split_connector")
    connectors = ConnectorEvaluator(store)
    nodes = connectors.nodes(entity.id)
    n = len(nodes.points)
    if isinstance(index, bool) or not isinstance(index, int) or not 0 < index < n - 1:
        _fail(entity.name, f"split index must be an interior node in (0, {n - 1}), got {index!r}")
    chain = connectors.chain(entity.id)
    arc = np.asarray(nodes.arc_positions)
    piece, t = chain.locate_length(float(arc[index]))
    segments = [dict(s) for s in entity.params["segments"]]
    first = segments[:piece]
    second = segments[piece + 1 :]
    seg = segments[piece]
    gap = 1e-12
    if abs(t - seg["t0"]) > gap:
        first.append({"curve": seg["curve"], "t0": seg["t0"], "t1": t})
    if abs(t - seg["t1"]) > gap:
        second.insert(0, {"curve": seg["curve"], "t0": t, "t1": seg["t1"]})
    if not first or not second:
        _fail(entity.name, f"node {index} cannot be split off (degenerate piece)")
    base = {"mode": "arc_length", "breakpoints": (), "propagate_spacing": True}
    head = dict(base, segments=first, dimension=index + 1, distribution=_explicit(arc[: index + 1]))
    tail = dict(base, segments=second, dimension=n - index, distribution=_explicit(arc[index:]))
    if new_name is None:
        new_name = fresh_name(store, f"{entity.name}-b")
    _update(store, entity.id, head)
    other = store.add("connector", normalize_params("connector", tail, new_name, store), new_name)
    _redirect(store, entity.id, [entity.id, other.id])
    return [entity.name, other.name], []


def _redirect(store, old: int, new_ids: list[int]) -> None:
    """Make every user of connector ``old`` use ``new_ids`` instead (in old's direction)."""
    for dependent in list(store.dependents(old)):
        params = dict(dependent.params)
        if dependent.kind == "domain":
            params["edges"] = tuple(
                tuple(_replace_in_chain(edge, old, new_ids)) for edge in params["edges"]
            )
        elif dependent.kind == "unstructured_domain":
            params["loops"] = tuple(
                tuple(_replace_in_chain(loop, old, new_ids)) for loop in params["loops"]
            )
            inflation = params["generator"]["inflation"]
            if inflation is not None and old in inflation["connectors"]:
                generator = dict(params["generator"])
                walls = []
                for c in inflation["connectors"]:
                    if c == old:
                        walls.extend(new_ids)
                    else:
                        walls.append(c)
                generator["inflation"] = dict(inflation, connectors=tuple(dict.fromkeys(walls)))
                params["generator"] = generator
        elif dependent.kind == "patch":
            members = []
            for item in params["members"]:
                if item.get("connector") == old:
                    members.extend({"connector": c} for c in new_ids)
                else:
                    members.append(item)
            unique = []
            for item in members:
                if item not in unique:
                    unique.append(item)
            params["members"] = tuple(unique)
        elif dependent.kind == "smoothing_group":
            walls = []
            for wall in params["walls"]:
                if wall["connector"] == old:
                    walls.extend(dict(wall, connector=c) for c in new_ids)
                else:
                    walls.append(wall)
            params["walls"] = tuple(walls)
            if params["slide"] != "auto" and old in params["slide"]:
                params["slide"] = tuple(c for c in params["slide"] if c != old) + tuple(new_ids)
        else:
            continue
        _update(store, dependent.id, params)


def join_connectors(store, first, second):
    a = _entity(store, first, "connector", "join_connectors")
    b = _entity(store, second, "connector", "join_connectors")
    if a.id == b.id:
        _fail(a.name, "cannot be joined with itself")
    connectors = ConnectorEvaluator(store)
    na = connectors.nodes(a.id)
    nb = connectors.nodes(b.id)
    scale = max(na.length, nb.length)
    pa = na.points
    pb = nb.points
    seg_a = [dict(s) for s in a.params["segments"]]
    seg_b = [dict(s) for s in b.params["segments"]]
    arc_a = np.asarray(na.arc_positions)
    arc_b = np.asarray(nb.arc_positions)
    # b oriented so that the joined connector runs along a's direction.
    if _same(pa[-1], pb[0], scale):
        b_first, b_reversed = False, False
    elif _same(pa[-1], pb[-1], scale):
        b_first, b_reversed = False, True
    elif _same(pa[0], pb[-1], scale):
        b_first, b_reversed = True, False
    elif _same(pa[0], pb[0], scale):
        b_first, b_reversed = True, True
    else:
        _fail(a.name, f"does not share an end with {b.name!r}")
    if b_reversed:
        seg_b = _segments_reversed(seg_b)
        arc_b = arc_b[-1] - arc_b[::-1]
    if b_first:
        segments = seg_b + seg_a
        arc = np.concatenate([arc_b, arc_b[-1] + arc_a[1:]])
    else:
        segments = seg_a + seg_b
        arc = np.concatenate([arc_a, arc_a[-1] + arc_b[1:]])
    # Users must take a and b consecutively; check before changing anything.
    users = {d.id: d for d in store.dependents(a.id)}
    users.update({d.id: d for d in store.dependents(b.id)})
    updates = {}
    for dependent in users.values():
        updates[dependent.id] = _joined_user(dependent, a.id, b.id, b_first, b_reversed)
    raw = {
        "segments": segments,
        "dimension": len(arc),
        "mode": "arc_length",
        "distribution": _explicit(arc),
        "breakpoints": (),
        "propagate_spacing": True,
    }
    _update(store, a.id, raw)
    for dependent_id, params in sorted(updates.items()):
        _update(store, dependent_id, params)
    store.remove(b.id)
    return [a.name], []


def _joined_user(dependent, a: int, b: int, b_first: bool, b_reversed: bool) -> dict:
    """Parameters of a user of a and b with the pair replaced by the joined connector a."""
    params = dict(dependent.params)
    if dependent.kind == "patch":
        has = {item.get("connector") for item in params["members"]}
        if (a in has) != (b in has):
            _fail(dependent.name, "holds only one of the connectors to join")
        params["members"] = tuple(m for m in params["members"] if m.get("connector") != b)
        return params
    if dependent.kind == "smoothing_group":
        # The joined connector keeps a's role (wall settings, sliding); b's entries go.
        params["walls"] = tuple(w for w in params["walls"] if w["connector"] != b)
        if params["slide"] != "auto":
            params["slide"] = tuple(c for c in params["slide"] if c != b)
        return params
    if dependent.kind not in ("domain", "unstructured_domain"):
        _fail(dependent.name, f"a {dependent.kind} uses the connectors; cannot join them")
    key = "edges"
    if dependent.kind == "unstructured_domain":
        key = "loops"
    chains = params[key]
    flat = [(k, m, item) for k, chain in enumerate(chains) for m, item in enumerate(chain)]
    uses_a = [x for x in flat if x[2]["connector"] == a]
    uses_b = [x for x in flat if x[2]["connector"] == b]
    if len(uses_a) != 1 or len(uses_b) != 1:
        _fail(dependent.name, "must use each connector to join exactly once")
    ka, ma, item_a = uses_a[0]
    kb, mb, item_b = uses_b[0]
    joined_reversed = item_a["reversed"]
    # b's item direction relative to the joined connector.
    if bool(item_b["reversed"]) != (joined_reversed != b_reversed):
        _fail(dependent.name, "uses the connectors in inconsistent directions")
    chain_list = [list(_items(c)) for c in chains]
    if dependent.kind == "unstructured_domain":
        inflation = params["generator"]["inflation"]
        if inflation is not None and b in inflation["connectors"]:
            walls = []
            for c in inflation["connectors"]:
                if c == b:
                    c = a
                walls.append(c)
            generator = dict(params["generator"])
            generator["inflation"] = dict(inflation, connectors=tuple(dict.fromkeys(walls)))
            params["generator"] = generator
    if dependent.kind == "domain":
        if ka != kb:
            _fail(dependent.name, "uses the connectors on different edges (a corner lies between)")
        chain = chain_list[ka]
        if abs(ma - mb) != 1:
            _fail(dependent.name, "does not use the connectors consecutively")
        # Traversal order: along a's direction b comes first iff b_first.
        b_before = mb < ma
        if b_before != (b_first != joined_reversed):
            _fail(dependent.name, "uses the connectors in an inconsistent order")
        lo = min(ma, mb)
        chain[lo : lo + 2] = [{"connector": a, "reversed": joined_reversed}]
        params[key] = tuple(tuple(c) for c in chain_list)
        return params
    if ka != kb:
        _fail(dependent.name, "uses the connectors in different loops")
    chain = chain_list[ka]
    size = len(chain)
    if size == 2:
        # The two connectors close the loop by themselves: it becomes the joined one.
        chain_list[ka] = [{"connector": a, "reversed": joined_reversed}]
        params[key] = tuple(tuple(c) for c in chain_list)
        return params
    if (ma - mb) % size not in (1, size - 1):
        _fail(dependent.name, "does not use the connectors consecutively")
    first_index = mb
    if (mb - ma) % size == 1:
        first_index = ma
    b_before = first_index == mb
    if b_before != (b_first != joined_reversed):
        _fail(dependent.name, "uses the connectors in an inconsistent order")
    rotated = chain[first_index:] + chain[:first_index]
    rotated = [{"connector": a, "reversed": joined_reversed}, *rotated[2:]]
    chain_list[ka] = rotated
    params[key] = tuple(tuple(c) for c in chain_list)
    return params


# ----------------------------------------------------------------------------- domains
def _split_chain_at(store, chain, node: int, where: str):
    """Split an edge chain at a node index (splitting a connector when needed). Returns the two
    chains (new item lists) and whether a connector was split (then the store changed)."""
    connectors = ConnectorEvaluator(store)
    counts = _chain_counts(chain, connectors)
    start = 0
    for m, (item, count) in enumerate(zip(chain, counts, strict=True)):
        end = start + count - 1
        if node == start and m > 0:
            return _items(chain[:m]), _items(chain[m:]), None
        if start < node < end:
            local = node - start
            if item["reversed"]:
                local = count - 1 - local
            names, _ = split_connector(store, item["connector"], local)
            return None, None, names
        start = end
    _fail(where, f"node {node} is not inside the edge")
    return None, None, None


def _domain_parts(store, entity_id: int, cuts) -> list[tuple[list, list]]:
    """Split edges of a domain at nodes: ``cuts`` = [(edge, node), ...]; returns the two chains
    of each edge (splitting a connector first when the node lies inside it)."""
    result = []
    for edge, node in cuts:
        where = store.get(entity_id).name
        chain = store.get(entity_id).params["edges"][edge]
        lo, hi, split = _split_chain_at(store, chain, node, where)
        if split is not None:
            chain = store.get(entity_id).params["edges"][edge]
            lo, hi, split = _split_chain_at(store, chain, node, where)
        result.append((lo, hi))
    return result


def _cut_connector(store, points: np.ndarray, base: str) -> int:
    """A connector on a polyline through ``points`` with its nodes exactly at the points."""
    curve_name = fresh_name(store, f"{base}-curve")
    _add(store, "polyline", {"points": [tuple(float(c) for c in p) for p in points]}, curve_name)
    chord = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))])
    connector = fresh_name(store, base)
    entity = _add(
        store,
        "connector",
        {
            "segments": curve_name,
            "dimension": len(points),
            "distribution": _explicit(chord),
        },
        connector,
    )
    return entity.id


def _filter_walls(generator: dict, keep: set[int]) -> tuple[dict, list[str]]:
    """Generator with walls only on the kept edges (0 / 2) and no attraction lines."""
    warnings = []
    g = dict(generator)
    g["hermite_walls"] = tuple(e for e in g["hermite_walls"] if e in keep)
    elliptic = g["elliptic"]
    if elliptic is not None:
        elliptic = dict(elliptic)
        elliptic["walls"] = tuple(w for w in elliptic["walls"] if w["edge"] in keep)
        if elliptic["attractions"]:
            warnings.append("attraction lines were dropped")
            elliptic["attractions"] = ()
        g["elliptic"] = elliptic
    return g, warnings


def _check_domain_users(store, entity, allowed_block=None):
    for dependent in store.dependents(entity.id):
        if dependent.kind == "block" and dependent.id != allowed_block:
            _fail(entity.name, f"is a face of block {dependent.name!r} (use split_block)")
        if dependent.kind == "patch":
            for item in dependent.params["members"]:
                if item.get("block") is not None:
                    _fail(dependent.name, "names block faces directly; cannot update it")


def _group_domains(params: dict, old: int, new_ids: list[int]) -> dict:
    """Smoothing-group parameters with domain ``old`` replaced by ``new_ids`` (member list of a
    2D group; walls and sliding faces of a 3D group, keeping their settings)."""
    params = dict(params)
    if old in params["domains"]:
        domains = []
        for d in params["domains"]:
            replacement = (d,)
            if d == old:
                replacement = tuple(new_ids)
            for e in replacement:
                if e not in domains:
                    domains.append(e)
        params["domains"] = tuple(domains)
    walls = []
    for wall in params["walls"]:
        if wall.get("domain") == old:
            walls.extend(dict(wall, domain=d) for d in new_ids)
        else:
            walls.append(wall)
    unique = []
    for wall in walls:
        if all(wall.get("domain") != w.get("domain") or "domain" not in wall for w in unique):
            unique.append(wall)
    params["walls"] = tuple(unique)
    if params["slide"] != "auto" and old in params["slide"]:
        rest = [d for d in params["slide"] if d != old]
        params["slide"] = tuple(dict.fromkeys(rest + list(new_ids)))
    return params


def _group_blocks(store, old: int, new_ids: list[int]) -> None:
    """Smoothing groups holding block ``old`` hold ``new_ids`` instead (or as well, when old is
    among them)."""
    for dependent in list(store.dependents(old)):
        if dependent.kind != "smoothing_group":
            continue
        blocks = []
        for b in dependent.params["blocks"]:
            replacement = (b,)
            if b == old:
                replacement = tuple(new_ids)
            for e in replacement:
                if e not in blocks and e in store:
                    blocks.append(e)
        _update(store, dependent.id, dict(dependent.params, blocks=tuple(blocks)))


def _add_to_users(store, old: int, new: int, skip_block=None) -> None:
    """Every zone, patch and volume holding domain ``old`` also holds ``new``."""
    for dependent in list(store.dependents(old)):
        params = dict(dependent.params)
        if dependent.kind == "zone" or dependent.kind == "patch":
            params["members"] = (*tuple(params["members"]), {"domain": new})
        elif dependent.kind == "volume":
            params["faces"] = (*tuple(params["faces"]), new)
        elif dependent.kind == "smoothing_group":
            params = _group_domains(params, old, [old, new])
        else:
            continue
        _update(store, dependent.id, params)


def split_domain(store, name, i: int | None = None, j: int | None = None, block=None):
    entity = _entity(store, name, "domain", "split_domain")
    if (i is None) == (j is None):
        _fail(entity.name, "give exactly one of i and j")
    _check_domain_users(store, entity, block)
    _connectors, domains = _evaluators(store)
    grid = np.asarray(domains.grid(entity.id))
    nj, ni = grid.shape[:2]
    index = i
    size = ni
    if j is not None:
        index = j
        size = nj
    if isinstance(index, bool) or not isinstance(index, int) or not 0 < index < size - 1:
        _fail(entity.name, f"split index must lie in (0, {size - 1}), got {index!r}")
    warnings = []
    if i is not None:
        (e0_lo, e0_hi), (e2_lo, e2_hi) = _domain_parts(store, entity.id, [(0, i), (2, ni - 1 - i)])
        cut = _cut_connector(store, grid[:, i], f"{entity.name}-cut")
        edges = store.get(entity.id).params["edges"]
        params = dict(store.get(entity.id).params)
        low = [e0_lo, [{"connector": cut, "reversed": False}], e2_hi, _items(edges[3])]
        high = [e0_hi, _items(edges[1]), e2_lo, [{"connector": cut, "reversed": True}]]
        low_generator, w1 = _filter_walls(params["generator"], {0, 2})
        high_generator = low_generator
        warnings.extend(w1)
    else:
        (e1_lo, e1_hi), (e3_lo, e3_hi) = _domain_parts(store, entity.id, [(1, j), (3, nj - 1 - j)])
        cut = _cut_connector(store, grid[j, :], f"{entity.name}-cut")
        edges = store.get(entity.id).params["edges"]
        params = dict(store.get(entity.id).params)
        low = [_items(edges[0]), e1_lo, [{"connector": cut, "reversed": True}], e3_hi]
        high = [[{"connector": cut, "reversed": False}], e1_hi, _items(edges[2]), e3_lo]
        low_generator, w1 = _filter_walls(params["generator"], {0})
        high_generator, _w2 = _filter_walls(params["generator"], {2})
        warnings.extend(w1)
    surface = params.get("surface")
    _update(store, entity.id, {"edges": low, "generator": low_generator, "surface": surface})
    other_name = fresh_name(store, f"{entity.name}-b")
    other = _add(
        store,
        "domain",
        {"edges": high, "generator": high_generator, "surface": surface},
        other_name,
    )
    _add_to_users(store, entity.id, other.id)
    return [entity.name, other.name, store.get(cut).name], warnings


def _rotate(edges, steps: int):
    steps %= 4
    return list(edges[steps:]) + list(edges[:steps])


def _add_face(store, edges, base: str, generator=None):
    """A new structured face; loops in a plane z = const are listed counter-clockwise (the 2D
    convention), others as given."""
    connectors = ConnectorEvaluator(store)
    loop = np.concatenate([_chain_points(e, connectors)[:-1] for e in edges])
    size = float(np.ptp(loop, axis=0).max())
    if float(np.ptp(loop[:, 2])) <= CHAIN_TOLERANCE * max(1.0, size):
        x = loop[:, 0]
        y = loop[:, 1]
        if float(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y)) < 0.0:
            edges = _flip(edges)
    raw = {"edges": edges, "generator": generator, "surface": None}
    return _add(store, "domain", raw, fresh_name(store, base))


def _flip(edges):
    """The same loop traversed the other way (a transposed grid)."""
    return [_reverse_chain(edges[k]) for k in (3, 2, 1, 0)]


def _remap_generator(generator: dict, steps: int, flipped: bool) -> tuple[dict, list[str]]:
    """Generator after rotating the edges by ``steps`` (and flipping): walls follow their edge
    when it stays an edge 0 / 2, otherwise they are dropped."""

    def new_index(e: int) -> int:
        if flipped:
            e = (3, 2, 1, 0)[e]
        return (e - steps) % 4

    g = dict(generator)
    warnings = []
    walls = [new_index(e) for e in g["hermite_walls"]]
    kept = tuple(sorted(e for e in walls if e in (0, 2)))
    if len(kept) != len(walls) and g["method"] == "hermite_tfi":
        warnings.append("Hermite walls not on edges 0 / 2 after joining were dropped")
    g["hermite_walls"] = kept
    if g["elliptic"] is not None:
        elliptic = dict(g["elliptic"])
        moved = []
        for w in elliptic["walls"]:
            e = new_index(w["edge"])
            if e in (0, 2):
                moved.append(dict(w, edge=e))
            else:
                warnings.append(f"elliptic wall on edge {w['edge']} was dropped")
        elliptic["walls"] = tuple(sorted(moved, key=lambda w: w["edge"]))
        if elliptic["attractions"]:
            warnings.append("attraction lines were dropped")
            elliptic["attractions"] = ()
        g["elliptic"] = elliptic
    return g, warnings


def _effective(generator: dict) -> dict:
    """Generator settings that matter (Hermite walls only for Hermite TFI)."""
    g = dict(generator)
    if g["method"] != "hermite_tfi":
        g["hermite_walls"] = ()
    return g


def _shared_edge(edges_a, edges_b):
    for ka, ea in enumerate(edges_a):
        ids_a = sorted(i["connector"] for i in ea)
        for kb, eb in enumerate(edges_b):
            if sorted(i["connector"] for i in eb) == ids_a:
                return ka, kb
    return None


def join_domains(store, first, second, allowed_blocks=()):
    a = _entity(store, first, "domain", "join_domains")
    b = _entity(store, second, "domain", "join_domains")
    if a.id == b.id:
        _fail(a.name, "cannot be joined with itself")
    for entity in (a, b):
        for dependent in store.dependents(entity.id):
            if dependent.kind == "block" and dependent.id not in allowed_blocks:
                _fail(entity.name, f"is a face of block {dependent.name!r} (use join_blocks)")
    if a.params.get("surface") != b.params.get("surface"):
        _fail(a.name, f"lies on a different surface than {b.name!r}")
    edges_a = [_items(e) for e in a.params["edges"]]
    edges_b = [_items(e) for e in b.params["edges"]]
    shared = _shared_edge(edges_a, edges_b)
    if shared is None:
        _fail(a.name, f"shares no whole edge with {b.name!r}")
    steps_a = (shared[0] - 1) % 4
    edges_a = _rotate(edges_a, steps_a)
    connectors = ConnectorEvaluator(store)
    flipped_b = False
    steps_b = (shared[1] - 3) % 4
    rotated_b = _rotate(edges_b, steps_b)
    start_a = _chain_points(edges_a[1], connectors)[0]
    start_b = _chain_points(rotated_b[3], connectors)[0]
    scale = float(np.ptp(_chain_points(edges_a[0], connectors), axis=0).max()) + 1.0
    if _same(start_a, start_b, scale):
        flipped_b = True
        edges_b = _flip(edges_b)
        shared_b = _shared_edge(edges_a, edges_b)[1]
        steps_b = (shared_b - 3) % 4
        rotated_b = _rotate(edges_b, steps_b)
    joined = [
        edges_a[0] + rotated_b[0],
        rotated_b[1],
        rotated_b[2] + edges_a[2],
        edges_a[3],
    ]
    generator, warnings = _remap_generator(a.params["generator"], steps_a, False)
    other, _w = _remap_generator(b.params["generator"], steps_b, flipped_b)
    if _effective(other) != _effective(generator):
        warnings.append(f"{b.name!r} had other generator settings; those of {a.name!r} are used")
    shared_connectors = {i["connector"] for i in edges_a[1]}
    _update(store, a.id, {"edges": joined, "generator": generator, "surface": a.params["surface"]})
    _replace_domain(store, b.id, a.id)
    store.remove(b.id)
    _drop_orphans(store, shared_connectors)
    return [a.name], warnings


def _replace_domain(store, old: int, new: int) -> None:
    """Users of domain ``old`` use ``new`` instead (no duplicates)."""
    for dependent in list(store.dependents(old)):
        params = dict(dependent.params)
        if dependent.kind in ("zone", "patch"):
            members = []
            for item in params["members"]:
                if item.get("domain") == old:
                    item = {"domain": new}
                if item not in members:
                    members.append(item)
            params["members"] = tuple(members)
        elif dependent.kind == "volume":
            faces = []
            for f in params["faces"]:
                if f == old:
                    f = new
                if f not in faces:
                    faces.append(f)
            params["faces"] = tuple(faces)
        elif dependent.kind == "smoothing_group":
            params = _group_domains(params, old, [new])
        else:
            continue
        _update(store, dependent.id, params)


def _drop_orphans(store, connector_ids) -> None:
    for c in sorted(connector_ids):
        if c in store and not store.dependents(c):
            store.remove(c)


