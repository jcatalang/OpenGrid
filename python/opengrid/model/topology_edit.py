def _six_face_block(store, name, where):
    entity = _entity(store, name, "block", where)
    if entity.params["faces"] is None:
        _fail(entity.name, "is an extruded block; only six-face blocks can be edited")
    for dependent in store.dependents(entity.id):
        if dependent.kind == "smoothing_group":
            continue  # updated by the edit
        _fail(entity.name, f"is used by {dependent.kind} {dependent.name!r}")
    return entity


def _block_eval(store, entity_id):
    from opengrid.model.blocks import BlockEvaluator

    _connectors, domains = _evaluators(store)
    return BlockEvaluator(store, domains).evaluate(entity_id)


def _block_params(entity, faces, warnings):
    smoothing = entity.params["smoothing"]
    if smoothing is not None and smoothing["walls"]:
        warnings.append(f"{entity.name}: smoothing walls were dropped (face names change)")
        smoothing = dict(smoothing, walls=())
    return {"faces": faces, "smoothing": smoothing, "quality_floor": entity.params["quality_floor"]}


def _line_in(domain_grid: np.ndarray, line: np.ndarray, scale: float):
    """("i", c) or ("j", r) when a grid column / row of the domain is the given line."""
    nj, ni = domain_grid.shape[:2]
    tolerance = CHAIN_TOLERANCE * max(1.0, scale)
    if len(line) == nj:
        for c in range(1, ni - 1):
            col = domain_grid[:, c]
            if np.abs(col - line).max() <= tolerance or np.abs(col[::-1] - line).max() <= tolerance:
                return "i", c
    if len(line) == ni:
        for r in range(1, nj - 1):
            row = domain_grid[r, :]
            if np.abs(row - line).max() <= tolerance or np.abs(row[::-1] - line).max() <= tolerance:
                return "j", r
    return None


def split_block(store, name, axis: str, index: int):
    entity = _six_face_block(store, name, "split_block")
    if axis not in AXES:
        _fail(entity.name, f"axis must be one of i, j, k, got {axis!r}")
    result = _block_eval(store, entity.id)
    grid = np.asarray(result["grid"])
    nk, nj, ni = grid.shape[:3]
    size = (ni, nj, nk)[AXES.index(axis)]
    if isinstance(index, bool) or not isinstance(index, int) or not 0 < index < size - 1:
        _fail(entity.name, f"split index must lie in (0, {size - 1}), got {index!r}")
    faces = result["faces"]
    ends = {"i": ("imin", "imax"), "j": ("jmin", "jmax"), "k": ("kmin", "kmax")}[axis]
    sides = [f for f in ("imin", "imax", "jmin", "jmax", "kmin", "kmax") if f not in ends]
    scale = float(np.ptp(grid.reshape(-1, 3), axis=0).max())
    low_faces = [faces[ends[0]]]
    high_faces = [faces[ends[1]]]
    cuts = []
    warnings = []
    for face in sides:
        domain_id = faces[face]
        line = _face_line(grid, face, axis, index)
        _c, domains = _evaluators(store)
        dgrid = np.asarray(domains.grid(domain_id))
        found = _line_in(dgrid, line, scale)
        if found is None:
            _fail(store.get(domain_id).name, "has no grid line along the cut")
        direction, at = found
        names, w = split_domain(store, domain_id, **{direction: at}, block=entity.id)
        warnings.extend(w)
        parts = [store.get(n).id for n in names[:2]]
        cuts.append(store.get(names[2]).id)
        low_side = _block_side_of(store, parts[0], grid, axis, index)
        if low_side:
            low_faces.append(parts[0])
            high_faces.append(parts[1])
        else:
            low_faces.append(parts[1])
            high_faces.append(parts[0])
    from opengrid.model.domains import assemble_edges

    connectors = ConnectorEvaluator(store)
    edges = assemble_edges(store, connectors, [store.get(c).name for c in cuts])
    mid = _add_face(store, [_items(e) for e in edges], f"{entity.name}-{axis}{index}")
    low_faces.append(mid.id)
    high_faces.append(mid.id)
    _update(store, entity.id, _block_params(entity, low_faces, warnings))
    other_name = fresh_name(store, f"{entity.name}-b")
    other = _add(store, "block", _block_params(entity, high_faces, []), other_name)
    _group_blocks(store, entity.id, [entity.id, other.id])
    return [entity.name, other.name, mid.name], warnings


def _face_line(grid, face, axis, index):
    """Points of block face ``face`` at index ``index`` along ``axis`` (an ordered line)."""
    a = AXES.index(axis)
    fixed = {"imin": (0, 0), "imax": (0, -1), "jmin": (1, 0), "jmax": (1, -1)}
    fixed.update({"kmin": (2, 0), "kmax": (2, -1)})
    face_axis, face_at = fixed[face]
    sl = [slice(None)] * 3  # (i, j, k) order
    sl[face_axis] = face_at
    sl[a] = index
    # grid is (k, j, i): reverse the slice order.
    return np.asarray(grid[sl[2], sl[1], sl[0]])


def _block_side_of(store, domain_id, grid, axis, index) -> bool:
    """True when the domain lies on the low side (index below ``index``) of the cut."""
    _c, domains = _evaluators(store)
    centre = np.asarray(domains.grid(domain_id)).reshape(-1, 3).mean(axis=0)
    a = AXES.index(axis)
    sl = [slice(None)] * 3
    sl[a] = 0
    low = np.asarray(grid[sl[2], sl[1], sl[0]]).reshape(-1, 3).mean(axis=0)
    sl[a] = -1
    high = np.asarray(grid[sl[2], sl[1], sl[0]]).reshape(-1, 3).mean(axis=0)
    return bool(np.linalg.norm(centre - low) < np.linalg.norm(centre - high))


def join_blocks(store, first, second):
    a = _six_face_block(store, first, "join_blocks")
    b = _six_face_block(store, second, "join_blocks")
    if a.id == b.id:
        _fail(a.name, "cannot be joined with itself")
    shared = set(a.params["faces"]) & set(b.params["faces"])
    if len(shared) != 1:
        _fail(a.name, f"must share exactly one face with {b.name!r} (shares {len(shared)})")
    face = shared.pop()
    for dependent in store.dependents(face):
        if dependent.id not in (a.id, b.id):
            _fail(store.get(face).name, f"is also used by {dependent.kind} {dependent.name!r}")
    face_edges = [_items(e) for e in store.get(face).params["edges"]]
    sides_a = [f for f in a.params["faces"] if f != face]
    sides_b = [f for f in b.params["faces"] if f != face]
    pairs = []
    for edge in face_edges:
        ids = sorted(i["connector"] for i in edge)

        def holder(candidates, ids=ids):
            for f in candidates:
                for e in store.get(f).params["edges"]:
                    if sorted(i["connector"] for i in e) == ids:
                        return f
            return None

        fa = holder(sides_a)
        fb = holder(sides_b)
        if fa is None or fb is None:
            _fail(store.get(face).name, "an edge of the shared face is not a whole side edge")
        pairs.append((fa, fb))
    end_a = [f for f in sides_a if f not in {p[0] for p in pairs}]
    end_b = [f for f in sides_b if f not in {p[1] for p in pairs}]
    if len(end_a) != 1 or len(end_b) != 1:
        _fail(a.name, "the blocks' faces do not pair up around the shared face")
    warnings = []
    joined = []
    edge_connectors = {i["connector"] for e in face_edges for i in e}
    for fa, fb in pairs:
        names, w = join_domains(store, fa, fb, allowed_blocks=(a.id, b.id))
        warnings.extend(w)
        joined.append(store.get(names[0]).id)
    faces = [end_a[0], end_b[0], *joined]
    _update(store, a.id, _block_params(a, faces, warnings))
    _group_blocks(store, b.id, [a.id])
    for dependent in list(store.dependents(face)):
        if dependent.kind == "smoothing_group":
            _update(store, dependent.id, _group_domains(dependent.params, face, []))
    store.remove(b.id)
    store.remove(face)
    _drop_orphans(store, edge_connectors)
    return [a.name], warnings


