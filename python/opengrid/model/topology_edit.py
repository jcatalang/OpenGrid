def convert_domain(store, name: str):
    """A structured domain becomes an unstructured one on the same connectors; an
    unstructured domain with one loop becomes a structured one (the loop assembled into four
    edges). The name stays; zones and 3D patches follow it. Refused for a sketch's domains
    (list the block in the sketch's unstructured blocks instead), members of a smoothing
    group and faces of blocks or volumes. Returns ([name], [])."""
    from opengrid.model.connectors import ConnectorEvaluator
    from opengrid.model.domains import assemble_edges
    from opengrid.model.entities import normalize_params
    from opengrid.model.sketch import owned_entities
    from opengrid.model.unstructured import assemble_loops

    entity = store.get(name)
    if entity.kind not in ("domain", "unstructured_domain"):
        raise ValidationError([Issue(str(name), f"is a {entity.kind}, not a domain")])
    owner = owned_entities(store).get(entity.id)
    if owner is not None:
        raise ValidationError(
            [
                Issue(
                    entity.name,
                    f"is generated by sketch {store.get(owner).name!r}: list its block in the "
                    "sketch's unstructured blocks instead",
                )
            ]
        )
    blockers = []
    for dependent in store.dependents(entity.id):
        if dependent.kind == "smoothing_group":
            blockers.append(f"smoothing group {dependent.name} (remove it from the group first)")
        elif dependent.kind in ("block", "volume"):
            blockers.append(f"{dependent.kind} {dependent.name}")
    if blockers:
        raise ValidationError(
            [Issue(entity.name, "cannot be converted while used by " + ", ".join(blockers))]
        )
    if entity.kind == "domain":
        ids = [item["connector"] for edge in entity.params["edges"] for item in edge]
    else:
        if len(entity.params["loops"]) != 1:
            raise ValidationError(
                [Issue(entity.name, "has holes: a structured domain has one loop of four edges")]
            )
        ids = [item["connector"] for item in entity.params["loops"][0]]
    names = []
    for connector_id in ids:
        connector = store.get(connector_id).name
        if connector not in names:
            names.append(connector)
    evaluator = ConnectorEvaluator(store)
    surface = entity.params.get("surface")
    if entity.kind == "domain":
        raw = {"loops": assemble_loops(store, evaluator, names, surface), "generator": None}
        new_kind = "unstructured_domain"
    else:
        raw = {"edges": assemble_edges(store, evaluator, names), "generator": None}
        new_kind = "domain"
    if surface is not None:
        raw["surface"] = surface
    # Zones and patches naming the domain: detached, then given the new entity.
    holders = []
    for holder in [*store.entities("zone"), *store.entities("patch")]:
        members = holder.params["members"]
        if any(item.get("domain") == entity.id for item in members):
            holders.append(holder.id)
            params = dict(holder.params)
            params["members"] = tuple(m for m in members if m.get("domain") != entity.id)
            store.update(holder.id, params=params)
    store.remove(entity.id)
    params = normalize_params(new_kind, raw, entity.name, store)
    new = store.add(new_kind, params, entity.name)
    for holder_id in holders:
        holder = store.get(holder_id)
        params = dict(holder.params)
        params["members"] = (*params["members"], {"domain": new.id})
        store.update(holder_id, params=params)
    return [new.name], []


