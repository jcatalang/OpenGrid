"""Deleting entities: dependents go along (on request; the GUI asks), patches / zones /
groups lose members instead of blocking, a sketch takes its outputs along, a sketch's domain
removes its block (Session.remove_sketch_blocks)."""

import pytest

import opengrid
from opengrid.project.ogp import to_json
from opengrid.validation import ValidationError


def square(og, name="d", origin=(0.0, 0.0)):
    x0, y0 = origin
    corners = ((x0, y0), (x0 + 1, y0), (x0 + 1, y0 + 1), (x0, y0 + 1))
    for k, side in enumerate(("b", "r", "t", "l")):
        og.create_line(corners[k], corners[(k + 1) % 4], name=f"{name}-{side}")
        og.create_connector(f"{name}-{side}", 5, name=f"{name}-c{side}")
    og.create_domain([[f"{name}-cb"], [f"{name}-cr"], [f"{name}-ct"], [f"{name}-cl"]], name=name)
    return og


def test_dependents_are_named_then_deleted_on_request():
    og = square(opengrid.Session())
    og.set_boundary_type(["d-cb"], "wall")
    og.create_zone("fluid", ["d"])
    og.create_smoothing_group(["d"], name="g")
    with pytest.raises(ValidationError, match="d-b: is used by connector 'd-cb'") as error:
        og.delete("d-b")
    assert "delete with dependents=True" in str(error.value)
    assert og.deletion_dependents("d-b") == ["d-cb", "d"]
    assert og.deletion_dependents("d") == []
    count = og.delete("d-b", dependents=True)
    assert count == 4  # the line, its connector, the domain and the emptied group
    assert "d" not in og.store and "d-cb" not in og.store and "g" not in og.store
    assert og.entity("wall").params["members"] == ()  # the patch stays, empty
    assert og.entity("fluid").params["members"] == ()
    og.undo()
    assert og.boundary_report().ok is False  # back as it was: d exists, three unassigned
    assert og.entity("g").params["domains"] == (og.entity("d").id,)
    og.redo()
    assert "d" not in og.store
    assert to_json(opengrid.replay(og.journal_text()).store) == to_json(og.store)


def test_membership_never_blocks_and_partners_unpair():
    og = square(opengrid.Session())
    og.set_boundary_type(["d-cb", "d-ct"], "wall")
    og.make_periodic_pair(["d-cl"], ["d-cr"])
    og.create_zone("fluid", ["d"])
    assert og.delete("d") == 1  # the domain alone: the connectors stay, the zone is emptied
    assert og.entity("fluid").params["members"] == ()
    assert og.entity("wall").params["members"] == (
        {"connector": og.entity("d-cb").id},
        {"connector": og.entity("d-ct").id},
    )
    og.undo()
    # Deleting a periodic patch unpairs its partner.
    og.delete("periodic-1b")
    assert og.entity("periodic-1a").params["periodic"] is None
    og.undo()
    og.delete("periodic-1a")
    assert "periodic-1b" in og.store and og.boundary_report().ok is False


def test_sketch_outputs_and_block_removal():
    og = opengrid.Session()
    og.create_sketch(
        [(0, 0), (1, 0), (1, 1), (0, 1), (2, 0), (2, 1)],
        [(0, 1, 2, 3), (1, 4, 5, 2)],
        spacing=0.25,
        walls={(0, 1): 1e-2, (1, 4): 1e-2},
        pinned=[(1, 2)],
        unstructured=[1],
        name="s",
    )
    og.set_boundary_type(["s-c0-1", "s-c1-4"], "wall")
    og.make_periodic_pair(["s-c0-3"], ["s-c4-5"])
    with pytest.raises(ValidationError, match=r"generated by sketch 's'.*remove its block"):
        og.delete("s-c0-1")
    with pytest.raises(ValidationError, match="generated by sketch 's'"):
        og.delete("s-d1")
    with pytest.raises(ValidationError, match="would remove every block"):
        og.remove_sketch_blocks("s", [0, 1])
    with pytest.raises(ValidationError, match="block 2 does not exist"):
        og.remove_sketch_blocks("s", 2)
    assert og.remove_sketch_blocks("s", 1) == "s"
    params = og.entity("s").params
    assert params["blocks"] == ((0, 1, 2, 3),)
    assert params["unstructured"] == ()
    assert [w["edge"] for w in params["walls"]] == [(0, 1)]  # the wall on (1, 4) went
    assert params["pinned"] == ((1, 2),)  # edge (1, 2) is still block 0's
    assert "s-d1" not in og.store and "s-c1-4" not in og.store and "s-c4-5" not in og.store
    assert og.names("domain") == ["s-d0"]
    assert og.entity("wall").params["members"] == ({"connector": og.entity("s-c0-1").id},)
    assert og.entity("periodic-1b").params["members"] == ()  # its connector went
    assert len(params["vertices"]) == 6  # the vertices stay
    og.undo()
    assert og.entity("s-d1").kind == "unstructured_domain"
    assert len(og.boundary_report().periodic) == 1  # the pair is whole again
    og.redo()
    # Removing block 0 renumbers: the remaining block's domain is s-d0 (unstructured now).
    og.undo()
    og.remove_sketch_blocks("s", 0)
    assert og.names("domain") == [] and og.names("unstructured_domain") == ["s-d0"]
    assert og.entity("s").params["blocks"] == ((1, 4, 5, 2),)
    assert og.entity("s").params["unstructured"] == (0,)
    og.undo()
    # The sketch itself goes with everything it generated, patches losing the members.
    assert og.delete("s") > 10
    assert og.names("connector") == [] and og.names("domain") == []
    assert og.entity("wall").params["members"] == ()
    assert to_json(opengrid.replay(og.journal_text()).store) == to_json(og.store)


def test_delete_in_the_gui(qtbot, monkeypatch):
    pytest.importorskip("PySide6")
    pytest.importorskip("pyvistaqt")
    from opengrid.app.main_window import MainWindow

    window = MainWindow(off_screen=True)
    qtbot.addWidget(window)
    og = window.session
    og.create_sketch(
        [(0, 0), (1, 0), (1, 1), (0, 1), (2, 0), (2, 1)],
        [(0, 1, 2, 3), (1, 4, 5, 2)],
        spacing=0.25,
        name="s",
    )
    og.set_boundary_type(["s-c0-1", "s-c1-4"], "wall")
    square(og, "q", origin=(0.0, 3.0))

    def ids(*names):
        return [og.entity(n).id for n in names]

    # A sketch's connector: a hint, nothing deleted.
    window.set_selection(ids("s-c0-1"))
    window.delete_selected()
    assert "s-c0-1" in og.store
    assert "delete the domain" in window.statusBar().currentMessage()
    # A sketch's domain: its block leaves the sketch.
    window.set_selection(ids("s-d1"))
    window.delete_selected()
    assert og.entity("s").params["blocks"] == ((0, 1, 2, 3),)
    assert "s-d1" not in og.store
    og.undo()
    # The last domain: the sketch goes, outputs included.
    window.set_selection(ids("s-d0", "s-d1"))
    window.delete_selected()
    assert "s" not in og.store and og.names("domain") == ["q"]
    og.undo()
    # A curve with dependents: the confirmation lists them; Cancel keeps everything.
    asked = []
    monkeypatch.setattr(
        window, "_confirm_deletion", lambda names, extra: asked.append((names, extra)) or False
    )
    window.set_selection(ids("q-b"))  # the shape of curve q-cb: the curve is selected
    window.delete_selected()
    assert asked == [(["q-cb"], ["q"])] and "q" in og.store
    monkeypatch.setattr(window, "_confirm_deletion", lambda names, extra: True)
    window.delete_selected()
    assert "q" not in og.store and "q-cb" not in og.store and "q-b" not in og.store
    assert "Deleted q-cb and 1 dependent entities" in window.statusBar().currentMessage()
    # A domain alone needs no confirmation.
    og.undo()
    window.set_selection(ids("q"))
    window.delete_selected()
    assert "q" not in og.store and "q-cb" in og.store
    window.close()
