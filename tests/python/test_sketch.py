    # The vertices went to the connector's ends (the drawn positions are kept as drawn).
    grid = og.domain_grid("sk-d0")
    assert np.allclose(sorted(grid[-1, [0, -1], 0]), [-1.0, 1.0], atol=1e-12)
    og.save(tmp_path / "adopt.ogp")
    other = opengrid.Session()
    other.load(tmp_path / "adopt.ogp")
    assert to_json(other.store) == to_json(og.store)
    assert replays(og)


