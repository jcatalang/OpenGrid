"""Phase 10d: sketch topology (a floating wireframe of blocks)."""

import math

import numpy as np
import pytest

import opengrid
from opengrid.project.ogp import to_json
from opengrid.validation import ValidationError

SQUARE = [(0, 0), (1, 0), (2, 0), (0, 1), (1.0, 1.0), (2, 1), (0, 2), (1, 2), (2, 2)]
SQUARE_BLOCKS = [(0, 1, 4, 3), (1, 2, 5, 4), (3, 4, 7, 6), (4, 5, 8, 7)]
SQUARE_DIMENSIONS = {(0, 1): 11, (1, 2): 11, (0, 3): 11, (3, 6): 11}


def replays(og) -> bool:
    return to_json(opengrid.replay(og.journal_text()).store) == to_json(og.store)


def grids(og) -> dict:
    out = {}
    for d in og.names("domain"):
        out[d] = og.domain_grid(d).copy()
    for b in og.names("block"):
        out[b] = og.block_grid(b).copy()
    return out


def largest_change(a: dict, b: dict) -> float:
    return max(float(np.abs(a[k] - b[k]).max()) for k in a)


def square(centre=(1.0, 1.0)) -> opengrid.Session:
    og = opengrid.Session()
    vertices = list(SQUARE)
    vertices[4] = centre
    og.create_sketch(vertices, SQUARE_BLOCKS, dimensions=SQUARE_DIMENSIONS, name="sk")
    return og


def test_interior_vertex_floats_and_outputs_are_ordinary_entities(tmp_path):
    og = square()
    assert og.names("domain") == ["sk-d0", "sk-d1", "sk-d2", "sk-d3"]
    assert og.entity("sk-group").kind == "smoothing_group"
    assert og.domain_dimensions("sk-d0") == (11, 11)
    reference = grids(og)
    # Drawn off-centre (by 20 % and 15 % of the block size): the same grid.
    for centre in ((1.2, 0.8), (0.85, 1.15)):
        assert largest_change(reference, grids(square(centre))) < 1e-6 * 0.1
    # Ordinary entities: patches, exports and quality work on them.
    og.create_patch("all", "wall", og.unassigned_boundary_connectors())
    path = tmp_path / "square.cgns"
    og.export_cgns(path)
    assert path.stat().st_size > 0
    assert (
        min(float(og.domain_quality(d)["scaled_jacobian"].min()) for d in og.names("domain")) > 0.99
    )


def test_undo_journal_and_project_round_trip(tmp_path):
    og = square((1.1, 0.9))
    og.edit_sketch("sk", dimensions={(0, 1): 13, (1, 2): 11, (0, 3): 11, (3, 6): 11})
    assert og.domain_dimensions("sk-d0") == (13, 11)
    assert replays(og)
    path = tmp_path / "sketch.ogp"
    og.save(path)
    loaded = opengrid.Session()
    loaded.load(path)
    assert to_json(loaded.store) == to_json(og.store)
    assert largest_change(grids(og), grids(loaded)) == 0.0
    og.undo()
    assert og.domain_dimensions("sk-d0") == (11, 11)
    og.undo()
    assert og.names() == []


def test_dimension_conflicts_and_missing_dimensions_are_reported_by_edge():
    og = opengrid.Session()
    with pytest.raises(ValidationError, match=r"\(0, 1\) and \(3, 4\).*11 and 13"):
        og.create_sketch(
            SQUARE, SQUARE_BLOCKS, dimensions={(0, 1): 11, (3, 4): 13, (1, 2): 5}, name="sk"
        )
    with pytest.raises(ValidationError, match="have no dimension"):
        og.create_sketch(SQUARE, SQUARE_BLOCKS, dimensions={(0, 1): 11}, name="sk")
    with pytest.raises(ValidationError, match="not an edge of the sketch"):
        og.create_sketch(SQUARE, SQUARE_BLOCKS, dimensions={(0, 8): 11}, spacing=0.1)
    assert og.names() == []


def test_outputs_are_owned_by_the_sketch():
    og = square()
    for attempt in (
        lambda: og.rename("sk-c0-1", "mine"),
        lambda: og.set_distribution("sk-c0-1", "tanh"),
        lambda: og.delete("sk-group"),
        lambda: og.split_domain("sk-d0", i=5),
    ):
        with pytest.raises(ValidationError, match="generated by sketch 'sk'"):
            attempt()
    # A patch on outputs survives regeneration (outputs keep their ids and names).
    og.create_patch("bottom", "wall", ["sk-c0-1", "sk-c1-2"])
    before = og.entity("sk-c0-1").id
    og.move_handle("sk", "vertices", 1, (1.05, 0.0, 0.0))
    assert og.entity("sk-c0-1").id == before
    assert og.journal_text().splitlines()[-1].startswith("og.move_handle('sk', 'vertices', 1")
    # Deleting the sketch deletes its outputs; the patch on them loses the members.
    og.delete("sk")
    assert og.names() == ["bottom"] and og.entity("bottom").params["members"] == ()
    og.delete("bottom")
    assert og.names() == []
    assert replays(og)


def half_annulus(og, inner_joint, outer_joint, curves=None) -> None:
    og.create_arc((0, 0), 1.0, 0.0, math.pi, name="inner")
    og.create_arc((0, 0), 2.0, 0.0, math.pi, name="outer")
    og.create_line((1, 0), (2, 0), name="right")
    og.create_line((-2, 0), (-1, 0), name="left")
    vertices = [(1, 0), (2, 0), (-1, 0), (-2, 0), inner_joint, outer_joint]
    blocks = [(0, 1, 5, 4), (4, 5, 3, 2)]
    dimensions = {(0, 1): 9, (0, 4): 17, (2, 4): 17}
    og.create_sketch(vertices, blocks, dimensions=dimensions, curves=curves or {}, name="half")


def test_assignment_is_offered_never_silent_and_joints_slide():
    og = opengrid.Session()
    half_annulus(og, (0.3, 0.9), (0.5, 1.9))
    # Nothing assigned: only the edges lying on curves are offered, nothing is snapped.
    found = og.sketch_suggestions("half")
    assert {item["curve"] for item in found} == {"left", "right"}
    assert og.entity("half").params["curves"] == ()
    assert any("not assigned" in w for w in og.last_warnings)
    og.assign_sketch_geometry("half", ["inner", "outer", "left", "right"])
    assigned = {
        item["edge"]: og.store.get(item["curve"]).name
        for item in og.entity("half").params["curves"]
    }
    assert assigned == {
        (0, 1): "right",
        (2, 3): "left",
        (0, 4): "inner",
        (2, 4): "inner",
        (1, 5): "outer",
        (3, 5): "outer",
    }
    # The joints slid along their arcs to the symmetry line; the nodes stay on the arcs.
    nodes = og.connector_nodes("half-c4-5").points
    assert abs(nodes[0][0]) < 1e-3 and abs(nodes[-1][0]) < 1e-3
    assert abs(np.linalg.norm(nodes[0]) - 1.0) < 1e-12
    assert "slides on inner" in og.sketch_report("half")
    # Drawn elsewhere: the same grid.
    other = opengrid.Session()
    half_annulus(other, (-0.4, 0.95), (-0.2, 2.1), curves=assigned)
    assert largest_change(grids(og), grids(other)) < 1e-2 * 0.1
    assert replays(og)


def test_internal_wall_keeps_its_spacing_and_pinned_edges_stay():
    og = opengrid.Session()
    vertices = [(0, -1), (2, -1), (2, 0), (0, 0), (2, 1), (0, 1)]
    blocks = [(0, 1, 2, 3), (3, 2, 4, 5)]
    og.create_sketch(
        vertices,
        blocks,
        dimensions={(0, 1): 21, (0, 3): 21, (3, 5): 21},
        walls={(2, 3): 0.005},
        name="cut",
    )
    og.smooth_group("cut-group")
    upper = og.domain_grid("cut-d1")
    lower = og.domain_grid("cut-d0")
    # First cells on both sides of the internal wall (y = 0), away from the ends.
    assert np.allclose(upper[1, 3:-3, 1], 0.005, rtol=0.05)
    assert np.allclose(lower[-2, 3:-3, 1], -0.005, rtol=0.05)
    assert np.allclose(upper[0, :, 1], 0.0)


def test_sketch_3d_wall_on_a_surface():
    og = opengrid.Session()
    r = 0.5
    og.create_arc((0, 0, 0), r, -math.pi / 2, math.pi / 2, normal=(0, -1, 0), name="mer")
    # Seam at +y: the +x cap has no seam or pole.
    og.create_revolved_surface(
        "mer", 2.5 * math.pi, axis=(0, 0, 1), start_angle=0.5 * math.pi, name="sphere"
    )
    c = r / math.sqrt(3)
    a = 1.0
    inner = [(c, -c, -c), (c, c, -c), (c, c, c), (c, -c, c)]
    outer = [(a, -a, -a), (a, a, -a), (a, a, a), (a, -a, a)]
    og.create_sketch(
        inner + outer,
        [(0, 1, 2, 3, 4, 5, 6, 7)],
        dimensions={(0, 1): 9, (0, 3): 9, (0, 4): 9},
        surfaces={(0, 1, 2, 3): "sphere"},
        walls={(0, 1, 2, 3): None},
        name="cap",
    )
    assert og.names("block") == ["cap-b0"]
    grid = og.block_grid("cap-b0")
    radius = np.linalg.norm(grid.reshape(-1, 3), axis=1)
    on_sphere = radius[radius < r * (1 + 1e-6)]
    assert len(on_sphere) == 81
    assert np.abs(on_sphere - r).max() < 1e-9
    assert float(og.block_quality("cap-b0")["scaled_jacobian"].min()) > 0.3
    assert replays(og)


def test_group_parameters_pinned_joints_and_slide_limit():
    og = opengrid.Session()
    og.create_line((0, 0), (2, 0), name="floor")
    og.create_line((2, 0), (2, 1), name="right")
    og.create_line((2, 1), (0, 1), name="roof")
    og.create_line((0, 1), (0, 0), name="left")
    og.create_line((1, 0), (1, 1), name="middle")
    for name, curve, t0, t1, n in (
        ("f1", "floor", 0.0, 0.5, 11),
        ("f2", "floor", 0.5, 1.0, 11),
        ("r1", "roof", 0.0, 0.5, 11),
        ("r2", "roof", 0.5, 1.0, 11),
        ("c", "middle", 0.0, 1.0, 11),
        ("cr", "right", 0.0, 1.0, 11),
        ("cl", "left", 0.0, 1.0, 11),
    ):
        og.create_connector([{"curve": curve, "t0": t0, "t1": t1}], n, name=name)
    og.create_domain([["f1"], ["c"], ["r2"], ["cl"]], name="a")
    og.create_domain([["f2"], ["cr"], ["r1"], [("c", True)]], name="b")
    group = og.create_smoothing_group(["a", "b"], joints="slide", name="g")
    result = og.smooth_group(group)
    assert result.node_counts["sliding"] == 4 * 9 + 2 * 9 + 2  # the two joints slide too
    og.modify(group, pinned=["c"])
    result = og.smooth_group(group)
    assert result.roles[og.entity("c").id] == "fixed"
    assert replays(og)


